function createRig(
  svgEl: SVGSVGElement,
  id: string,
  initialGrowthLevel: number,
  alive: { current: boolean }
): { handle: RigHandle; stop: () => void } | null {
  const $ = (elemId: string) => svgEl.querySelector<SVGElement>(`#${id}-${elemId}`) as SVGElement;

  const root      = $('root');
  const handLeft  = $('Hand_Left');
  const handRight = $('Hand_Right');
  const mouth     = $('Mouth');
  const foreLegL  = $('Fore_Leg_Left');
  const foreLegR  = $('Fore_Leg_Right');
  const hindLegL  = $('Hind_Leg_Left');
  const hindLegR  = $('Hind_Leg_RIght'); // typo in source Figma layer preserved

  if (!root || !handLeft || !handRight || !mouth || !foreLegL || !foreLegR || !hindLegL || !hindLegR) return null;

  // Eye groups: blink via scaleY around their centre
  const eyeConfigs = [
    { el: $('Eye_1'), cx: 73,  cy: 78  },
    { el: $('Eye_2'), cx: 134, cy: 36  },
    { el: $('Eye_3'), cx: 191, cy: 78  },
    { el: $('Eye_4'), cx: 143, cy: 158 },
  ];

  // Pupils: translate offsets for darting (note mixed capitalisation preserved)
  const pupilEls = [
    $('Eye_ball_1'), // lowercase 'ball'
    $('Eye_Ball_2'),
    $('Eye_Ball_3'),
    $('Eye_Ball_4'),
  ];

  const MARCH_SPEED    = 3.0;
  const MARCH_LIFT     = 12;   // degrees — don't raise, see spec note
  const MARCH_COMPRESS = 0.08; // scaleY delta — don't raise

  const PUPIL_RADIUS = 3;

  const state = {
    voteScale:   1,
    voteRotate:  0,
    growScale:   initialGrowthLevel,
    squatY:      1,
    squatX:      1,
    dancing:     false,
    danceStart:  0,
    mouthScaleY: 1,
    mouthTarget: 1,
    blinkScaleY: 1,
    pupilState:  pupilEls.map(() => ({ cx: 0, cy: 0, tcx: 0, tcy: 0 })),
  };

  // --- BLINK ---
  function blink() {
    const duration = 150;
    const startTime = performance.now();
    function step(now: number) {
      if (!alive.current) return;
      const t = (now - startTime) / duration;
      if (t >= 1) { state.blinkScaleY = 1; return; }
      const phase = t < 0.5 ? t / 0.5 : 1 - (t - 0.5) / 0.5;
      state.blinkScaleY = 1 - phase * 0.95;
      requestAnimationFrame(step);
    }
    requestAnimationFrame(step);
  }

  function scheduleBlink() {
    const delay = 1800 + Math.random() * 2200;
    setTimeout(() => {
      if (!alive.current) return;
      blink();
      if (Math.random() < 0.3) setTimeout(() => { if (alive.current) blink(); }, 200);
      if (alive.current) scheduleBlink();
    }, delay);
  }

  // --- RAPID EYE DARTS ---
  function scheduleEyeDart() {
    const delay = 400 + Math.random() * 900;
    setTimeout(() => {
      if (!alive.current) return;
      const idx = Math.floor(Math.random() * 4);
      const angle = Math.random() * Math.PI * 2;
      const dist = Math.random() * PUPIL_RADIUS;
      state.pupilState[idx].tcx = Math.cos(angle) * dist;
      state.pupilState[idx].tcy = Math.sin(angle) * dist;
      scheduleEyeDart();
    }, delay);
  }

  // --- MOUTH ---
  function scheduleMouth() {
    const delay = 1500 + Math.random() * 2500;
    setTimeout(() => {
      if (!alive.current) return;
      state.mouthTarget = state.mouthTarget > 1 ? 1 : 1.6;
      scheduleMouth();
    }, delay);
  }

  // --- DANCE ---
  function triggerDance() {
    state.dancing    = true;
    state.danceStart = performance.now();
  }

  // --- VOTE WOBBLE ---
  function triggerVote() {
    const startTime = performance.now();
    const duration  = 450;
    function step(now: number) {
      if (!alive.current) return;
      const t = (now - startTime) / duration;
      if (t >= 1) { state.voteScale = 1; state.voteRotate = 0; return; }
      const damp = Math.exp(-3.5 * t);
      state.voteRotate = damp * Math.sin(t * Math.PI * 6) * 5;
      state.voteScale  = 1 + damp * Math.sin(t * Math.PI * 4) * 0.05;
      requestAnimationFrame(step);
    }
    requestAnimationFrame(step);
    triggerDance();
  }

  // --- GROW ---
  function triggerGrow(targetScale: number) {
    const startScale = state.growScale;
    const duration   = 1800;
    const startTime  = performance.now();
    function step(now: number) {
      if (!alive.current) return;
      const t = Math.min((now - startTime) / duration, 1);

      if (t < 0.25) {
        const p     = t / 0.25;
        const eased = p * p;
        state.squatY    = 1 - eased * 0.18;
        state.squatX    = 1 + eased * 0.10;
        state.growScale = startScale;
      } else if (t < 0.7) {
        const p   = (t - 0.25) / 0.45;
        const c1  = 2.2;
        const c3  = c1 + 1;
        const eased       = 1 + c3 * Math.pow(p - 1, 3) + c1 * Math.pow(p - 1, 2);
        state.growScale   = startScale + (targetScale - startScale) * eased;
        const stretchEase = 1 - Math.pow(1 - p, 3);
        state.squatY = 0.82 + stretchEase * 0.22;
        state.squatX = 1.10 - stretchEase * 0.14;
      } else {
        const p     = (t - 0.7) / 0.3;
        const eased = 1 - Math.pow(1 - p, 2);
        state.squatY    = 1.04 - eased * 0.04;
        state.squatX    = 0.96 + eased * 0.04;
        state.growScale = targetScale;
      }

      if (t < 1) {
        requestAnimationFrame(step);
      } else {
        state.squatY    = 1;
        state.squatX    = 1;
        state.growScale = targetScale;
      }
    }
    requestAnimationFrame(step);
    triggerDance();
  }

  // Helper: leg transform — rotate around hip + scaleY compress (knee-bend cheat)
  function setLeg(el: SVGElement, lift: number, dir: number, hx: number, hy: number) {
    const angle    = lift * MARCH_LIFT * dir;
    const compress = 1 - lift * MARCH_COMPRESS;
    el.setAttribute('transform',
      `translate(${hx} ${hy}) rotate(${angle}) scale(1 ${compress}) translate(${-hx} ${-hy})`
    );
  }

  const GROUND_Y = 335;
  const PIVOT_X  = 128;

  let lastTime  = performance.now();
  let rafHandle = 0;

  function frame(now: number) {
    if (!alive.current) return;
    const dt = Math.min((now - lastTime) / 1000, 0.05);
    lastTime = now;
    const t = now / 1000;

    // Root — no breath, just grow + vote + squat from ground
    const totalScaleY = state.growScale * state.voteScale * state.squatY;
    const totalScaleX = state.growScale * state.voteScale * state.squatX;
    root.setAttribute('transform',
      `translate(${PIVOT_X} ${GROUND_Y}) scale(${totalScaleX} ${totalScaleY}) rotate(${state.voteRotate}) translate(${-PIVOT_X} ${-GROUND_Y})`
    );

    // Marching legs — alternating diagonal pairs
    const marchPhase = Math.sin(t * MARCH_SPEED);
    const pairA = Math.max(0,  marchPhase);
    const pairB = Math.max(0, -marchPhase);
    setLeg(foreLegL, pairA,  1, 103, 280);
    setLeg(hindLegR, pairA, -1, 175, 275);
    setLeg(foreLegR, pairB, -1, 155, 280);
    setLeg(hindLegL, pairB,  1,  83, 275);

    // Hands — idle sway or dance burst
    let handLA: number, handRA: number;
    if (state.dancing) {
      const elapsed = (now - state.danceStart) / 1000;
      if (elapsed >= 2.2) {
        state.dancing = false;
        handLA = 0;
        handRA = 0;
      } else {
        const damp = 1 - elapsed / 2.2;
        const beat = Math.sin(elapsed * Math.PI * 6);
        handLA =  beat * 22 * damp;
        handRA = -beat * 22 * damp;
      }
    } else {
      handLA =  Math.sin(t * 1.5) * 4;
      handRA =  Math.sin(t * 1.5 + Math.PI) * 4;
    }
    handLeft.setAttribute('transform',  `rotate(${handLA} 81 166)`);
    handRight.setAttribute('transform', `rotate(${handRA} 192 152)`);

    // Mouth scaleY — springy open/close from centre
    state.mouthScaleY += (state.mouthTarget - state.mouthScaleY) * 0.15;
    mouth.setAttribute('transform',
      `translate(131 232) scale(1 ${state.mouthScaleY}) translate(-131 -232)`
    );

    // Eye blink — all 4 eyes scale vertically around their centres
    for (const ec of eyeConfigs) {
      if (!ec.el) continue;
      ec.el.setAttribute('transform',
        `translate(${ec.cx} ${ec.cy}) scale(1 ${state.blinkScaleY}) translate(${-ec.cx} ${-ec.cy})`
      );
    }

    // Rapid pupil darting — high lerp factor for snappy twitchy movement
    for (let i = 0; i < 4; i++) {
      const ps = state.pupilState[i];
      ps.cx += (ps.tcx - ps.cx) * 0.25;
      ps.cy += (ps.tcy - ps.cy) * 0.25;
      if (pupilEls[i]) {
        pupilEls[i].setAttribute('transform', `translate(${ps.cx} ${ps.cy})`);
      }
    }

    rafHandle = requestAnimationFrame(frame);
  }

  scheduleBlink();
  scheduleEyeDart();
  scheduleMouth();
  rafHandle = requestAnimationFrame(frame);

  return {
    handle: {
      triggerVote,
      triggerGrow,
      syncScale: (target: number) => { state.growScale = target; },
    },
    stop: () => cancelAnimationFrame(rafHandle),
  };
}

