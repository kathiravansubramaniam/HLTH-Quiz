function createRig(
  svgEl: SVGSVGElement,
  id: string,
  initialGrowthLevel: number,
  alive: { current: boolean }
): { handle: RigHandle; stop: () => void } | null {
  const $ = (elemId: string) =>
    svgEl.querySelector<SVGElement>(`#${id}-${elemId}`) as SVGElement;

  const root       = $('root');
  const wing       = $('Wing');
  const bodyFrame  = $('Body_Frame');
  const pupilSmall = $('Eye');
  const pupilBig   = $('Eye_big');
  const eyelidS    = $('eyelid-small');
  const eyelidB    = $('eyelid-big');
  const handUp     = $('Hand_Up');
  const handDown   = $('Hand_Down');
  const mouth      = $('Mouth');

  if (!root || !wing || !bodyFrame || !pupilSmall || !pupilBig ||
      !eyelidS || !eyelidB || !handUp || !handDown || !mouth) return null;

  const EYELID_S_REST   = 22;
  const EYELID_S_CLOSED = 45;
  const EYELID_B_REST   = 15;
  const EYELID_B_CLOSED = 39;

  const state = {
    growScale:        initialGrowthLevel,
    squatY:           1,
    squatX:           1,
    wobbleBoostAmt:   0,   // 0=none, decays from 1.4 on vote
    mouthCurrent:     0,
    mouthTarget:      0,
    eyelidSY:         EYELID_S_REST,
    eyelidBY:         EYELID_B_REST,
    pupilSAngle:      0,
    pupilBAngle:      Math.PI,
  };

  // ── Blink ───────────────────────────────────────────────────────────────────
  function blinkEye(
    restY: number,
    closedY: number,
    getY: () => number,
    setY: (v: number) => void
  ) {
    const duration = 210;
    const start = performance.now();
    function step(now: number) {
      if (!alive.current) return;
      const t = (now - start) / duration;
      if (t >= 1) { setY(restY); return; }
      const phase = t < 0.5 ? t / 0.5 : 1 - (t - 0.5) / 0.5;
      setY(restY + (closedY - restY) * phase);
      void getY;
      requestAnimationFrame(step);
    }
    requestAnimationFrame(step);
  }

  function scheduleBlinkS() {
    setTimeout(() => {
      if (!alive.current) return;
      blinkEye(EYELID_S_REST, EYELID_S_CLOSED, () => state.eyelidSY, (v) => { state.eyelidSY = v; });
      if (Math.random() < 0.18) setTimeout(() => {
        if (alive.current) blinkEye(EYELID_S_REST, EYELID_S_CLOSED, () => state.eyelidSY, (v) => { state.eyelidSY = v; });
      }, 280);
      if (alive.current) scheduleBlinkS();
    }, 2000 + Math.random() * 3000);
  }

  function scheduleBlinkB() {
    setTimeout(() => {
      if (!alive.current) return;
      blinkEye(EYELID_B_REST, EYELID_B_CLOSED, () => state.eyelidBY, (v) => { state.eyelidBY = v; });
      if (Math.random() < 0.18) setTimeout(() => {
        if (alive.current) blinkEye(EYELID_B_REST, EYELID_B_CLOSED, () => state.eyelidBY, (v) => { state.eyelidBY = v; });
      }, 280);
      if (alive.current) scheduleBlinkB();
    }, 1700 + Math.random() * 3500);
  }

  // ── Vote ─────────────────────────────────────────────────────────────────────
  function triggerVote() {
    state.wobbleBoostAmt = 1.4;
    state.mouthTarget    = 0.7;
    setTimeout(() => { if (alive.current) state.mouthTarget = 0; }, 700);
  }

  // ── Grow ─────────────────────────────────────────────────────────────────────
  function triggerGrow(targetScale: number) {
    const startScale = state.growScale;
    const duration   = 1800;
    const start      = performance.now();
    function step(now: number) {
      if (!alive.current) return;
      const t = Math.min((now - start) / duration, 1);
      if (t < 0.25) {
        const p = t / 0.25;
        const e = p * p;
        state.squatY    = 1 - e * 0.18;
        state.squatX    = 1 + e * 0.10;
        state.growScale = startScale;
      } else if (t < 0.7) {
        const p  = (t - 0.25) / 0.45;
        const c1 = 2.2;
        const c3 = c1 + 1;
        const e  = 1 + c3 * Math.pow(p - 1, 3) + c1 * Math.pow(p - 1, 2);
        state.growScale = startScale + (targetScale - startScale) * e;
        const se        = 1 - Math.pow(1 - p, 3);
        state.squatY    = 0.82 + se * 0.22;
        state.squatX    = 1.10 - se * 0.14;
      } else {
        const p      = (t - 0.7) / 0.3;
        const e      = 1 - Math.pow(1 - p, 2);
        state.squatY = 1.04 - e * 0.04;
        state.squatX = 0.96 + e * 0.04;
        state.growScale = targetScale;
      }
      if (t < 1) { requestAnimationFrame(step); }
      else { state.squatY = 1; state.squatX = 1; state.growScale = targetScale; }
    }
    requestAnimationFrame(step);
    state.mouthTarget = 1;
    setTimeout(() => { if (alive.current) state.mouthTarget = 0; }, 1600);
  }

  // ── Main loop ─────────────────────────────────────────────────────────────────
  const PIVOT_X = 150;
  const PIVOT_Y = 258;
  let lastTime  = performance.now();
  let rafHandle = 0;

  function frame(now: number) {
    if (!alive.current) return;
    const dt = Math.min((now - lastTime) / 1000, 0.05);
    lastTime = now;
    const t  = now / 1000;

    // Decay wobble boost linearly over 1.5s
    if (state.wobbleBoostAmt > 0) {
      state.wobbleBoostAmt = Math.max(0, state.wobbleBoostAmt - (1.4 / 1.5) * dt);
    }
    const wobbleBoost = 1.0 + state.wobbleBoostAmt;

    // Balance wobble — two overlapping sine waves for organic feel
    const wobble = (Math.sin(t * 0.9) * 0.7 + Math.sin(t * 1.7) * 0.3) * 4 * wobbleBoost;

    // Root: scale from foot + wobble rotation around foot
    const sx = state.growScale * state.squatX;
    const sy = state.growScale * state.squatY;
    root.setAttribute('transform',
      `translate(${PIVOT_X} ${PIVOT_Y}) ` +
      `scale(${sx} ${sy}) ` +
      `rotate(${wobble}) ` +
      `translate(${-PIVOT_X} ${-PIVOT_Y})`
    );

    // Wing: fast 12Hz flap counter-balanced against wobble
    const wingRot = -wobble * 1.8 + Math.sin(t * 12) * 15 * wobbleBoost;
    wing.style.transform = `rotate(${wingRot}deg)`;

    // Hand_Up: slower 3.2Hz flap
    const flapBase  = -wobble * 1.8;
    const handUpRot = flapBase * 0.6 + Math.sin(t * 3.2 + 0.5) * 5 * wobbleBoost;
    handUp.style.transform = `rotate(${handUpRot}deg)`;

    // Hand_Down: barely reacts
    handDown.style.transform = `rotate(${wobble * 0.15}deg)`;

    // Body_Frame: subtle breathing
    bodyFrame.style.transform = `scaleY(${1 + Math.sin(t * 1.2) * 0.025})`;

    // Mouth
    state.mouthCurrent += (state.mouthTarget - state.mouthCurrent) * 0.2;
    (mouth as SVGPathElement).style.transform = `scaleY(${1 + state.mouthCurrent * 0.9})`;

    // Pupils: independent orbits, opposite directions
    state.pupilSAngle += 0.6  * dt;
    state.pupilBAngle -= 0.85 * dt;
    const ORBIT_S = 3;
    const ORBIT_B = 4.5;
    pupilSmall.setAttribute('transform',
      `translate(${Math.cos(state.pupilSAngle) * ORBIT_S} ${Math.sin(state.pupilSAngle) * ORBIT_S})`
    );
    pupilBig.setAttribute('transform',
      `translate(${Math.cos(state.pupilBAngle) * ORBIT_B} ${Math.sin(state.pupilBAngle) * ORBIT_B})`
    );

    // Eyelids (independent)
    const blinkingS = state.eyelidSY > EYELID_S_REST + 0.5;
    eyelidS.setAttribute('cy', String(state.eyelidSY));
    eyelidS.setAttribute('opacity', blinkingS ? '1' : '0');

    const blinkingB = state.eyelidBY > EYELID_B_REST + 0.5;
    eyelidB.setAttribute('cy', String(state.eyelidBY));
    eyelidB.setAttribute('opacity', blinkingB ? '1' : '0');

    rafHandle = requestAnimationFrame(frame);
  }

  scheduleBlinkS();
  scheduleBlinkB();
  rafHandle = requestAnimationFrame(frame);

  return {
    handle: {
      triggerVote,
      triggerGrow,
      syncScale: (target: number) => { state.growScale = target; },
    },
    stop: () => cancelAnimationFrame(rafHandle),
  };
}

